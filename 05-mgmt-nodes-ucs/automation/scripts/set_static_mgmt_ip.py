#!/usr/bin/env python3
"""Move CIMC / BMC management interfaces from their DHCP bootstrap address to a static address over Redfish.

Reads the stage inventory generated by the Automation UI. A host is converted when its ``ucs.cimc`` entry has a
``dhcp_ip`` (current address) and ``ip`` (static target; it may equal the current address). A missing ``netmask`` or
``gateway`` is read from the address the device has now. Passwords come from the environment variable named by
``ucs.cimc.pass_ref``. Without ``--apply`` the script only reports the plan.
"""

from __future__ import annotations

import argparse
import sys
import time
from pathlib import Path

import requests

sys.path.insert(0, str(Path(__file__).resolve().parents[3]))
from shared.lib.redfish import Redfish, RedfishError, endpoints, password  # noqa: E402

REDFISH_ROLES = ("ucs-server", "hgx-node")


def reachable(address: str, user: str, secret: str) -> bool:
    try:
        Redfish(address, user, secret, timeout=8).get("/redfish/v1/Managers")
        return True
    except (RedfishError, requests.RequestException, ValueError):
        return False


def convert(name: str, ucs: dict, apply: bool, wait: int) -> str:
    cimc = ucs.get("cimc") or {}
    target, current = cimc.get("ip"), cimc.get("dhcp_ip")
    if ucs.get("device_role") not in REDFISH_ROLES:
        return "skip: Fabric Interconnect / X-Direct addresses are set during the initial device setup"
    if not current:
        return "skip: no current (DHCP) address on the Claim Targets page"
    target = target or current
    secret = password(ucs)
    user = cimc.get("user", "admin")
    if target != current and reachable(target, user, secret):
        return f"ok: already answering on {target}"
    client = Redfish(current, user, secret)
    path, data = client.manager_interface(current)
    dhcp = (data.get("DHCPv4") or {}).get("DHCPEnabled")
    if target == current and dhcp is False:
        return f"ok: {target} is already static"
    live = next((item for item in data.get("IPv4Addresses") or [] if item.get("Address") == current), {})
    netmask = cimc.get("netmask") or live.get("SubnetMask", "")
    gateway = cimc.get("gateway") or live.get("Gateway", "")
    if not netmask or not gateway:
        return "failed: netmask or gateway is not set and the device does not report one"
    cimc = {**cimc, "netmask": netmask, "gateway": gateway}
    print(f"  {name}: {path} DHCP={dhcp} {current} -> {target}/{netmask} gw {gateway}", flush=True)
    if not apply:
        return "planned"
    body = {"DHCPv4": {"DHCPEnabled": False},
            "IPv4StaticAddresses": [{"Address": target, "SubnetMask": cimc["netmask"], "Gateway": cimc["gateway"]}]}
    try:
        response = client.patch(path, body)
        if response.status_code >= 400:
            return f"failed: HTTP {response.status_code} {response.text[:300]}"
    except requests.RequestException:
        pass  # the BMC usually drops the session while it changes address
    deadline = time.time() + wait
    while time.time() < deadline:
        time.sleep(10)
        if reachable(target, user, secret):
            return f"ok: now answering on {target}"
    return f"failed: {target} did not answer within {wait}s; check the console or the DHCP lease"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--inventory-dir", type=Path, required=True, help="UI-generated stage inventory directory")
    parser.add_argument("--host", action="append", default=[], help="limit to these inventory hosts")
    parser.add_argument("--apply", action="store_true", help="make the change (default: report only)")
    parser.add_argument("--wait", type=int, default=240, help="seconds to wait for the new address")
    args = parser.parse_args()
    hosts = endpoints(args.inventory_dir)
    if args.host:
        hosts = {name: value for name, value in hosts.items() if name in args.host}
    if not hosts:
        print("No UCS endpoints in the inventory. Assign roles on the Initial Inventory page.")
        return 1
    failures = 0
    print(("Applying" if args.apply else "Planning") + f" static management addresses for {len(hosts)} hosts", flush=True)
    for name, ucs in hosts.items():
        try:
            result = convert(name, ucs, args.apply, args.wait)
        except (RedfishError, requests.RequestException, KeyError) as error:
            result = f"failed: {error}"
        failures += result.startswith("failed")
        print(f"{name:<28} {result}", flush=True)
    return 1 if failures else 0


if __name__ == "__main__":
    raise SystemExit(main())

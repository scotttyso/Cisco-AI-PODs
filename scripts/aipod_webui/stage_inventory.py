"""Render the workflow-stage Ansible inventory from the UI's schema YAML and initial inventory.

The stage playbooks merged from Cisco-AI-PODs-DEV read a canonical inventory
(inventory.yml, group_vars, host_vars) and per-host ``pass_ref`` names whose
values live in the vault as ``vault_<pass_ref lower>``.  This module produces that
inventory under ``<output>/inventory`` so the stages run against site data instead
of the lab examples, and reports which vault keys each stage needs.
"""

import ipaddress
import re
from pathlib import Path

import yaml

from .seeds import by_role, domain_name, host_key, is_claimable, row_role

ND_HOSTS = ("nd-1", "nd-2", "nd-3")
ND_INTERNAL = {"app_network": "172.17.0.1/16", "service_network": "100.80.0.0/16"}


def pass_ref(name: str, suffix: str) -> str:
    return re.sub(r"[^A-Z0-9]+", "_", name.upper()).strip("_") + f"_{suffix}"


def vault_key(reference: str) -> str:
    return "vault_" + reference.lower()


def _prefix(mask) -> int:
    if isinstance(mask, int):
        return mask
    try:
        return ipaddress.ip_network(f"0.0.0.0/{mask}").prefixlen
    except ValueError:
        return int(str(mask).lstrip("/"))


def _load(path: Path) -> dict:
    try:
        data = yaml.safe_load(path.read_text(encoding="utf-8")) if path.is_file() else {}
    except (OSError, yaml.YAMLError):
        return {}
    return data if isinstance(data, dict) else {}


def _write(path: Path, data) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("---\n# Generated by the Automation UI. Edit the UI pages instead.\n"
                    + yaml.safe_dump(data, sort_keys=False, default_flow_style=False), encoding="utf-8")


def nd_cluster_vars(cluster: dict, services: dict) -> tuple[dict, dict[str, dict]]:
    """Map nexus_dashboard.cluster (schema) to stage-01 group_vars and per-node host_vars."""
    iso = cluster.get("iso") or {}
    url = str(iso.get("url", "")).rstrip("/")
    if iso.get("file_path"):
        url = f"{url}/{str(iso['file_path']).lstrip('/')}"
    proxy = cluster.get("proxy") or {}
    proxy_url = proxy.get("https_proxy") or proxy.get("http_proxy")
    runtime = cluster.get("runtime") or {}
    spec = {
        "start_mode": cluster.get("start_mode", "iso_reimage"),
        "name": cluster.get("name", ""),
        "implementation_type": cluster.get("implementation_type", "LAN"),
        "iso": {"url": url, "sha512": iso.get("sha512", "")},
        "network": {key: value for key, value in (cluster.get("network") or {}).items() if value},
        "internal_networks": cluster.get("internal_networks") or dict(ND_INTERNAL),
        "proxy": {"skip": False, "url": proxy_url, "ignore_hosts": list(proxy.get("no_proxy") or [])}
        if proxy_url else {"skip": True},
        "external_services": {"management_service_ips": [], "data_service_ips": list(cluster.get("persistent_ips") or [])},
    }
    group = {
        "nd_admin_username": cluster.get("admin_username", "admin"),
        "nd_admin_pass_ref": "ND_ADMIN_PASSWORD",
        "nd_cluster_spec": spec,
        "nd_runtime": {"state_dir": runtime.get("state_dir", "state/"), "ca_bundle": runtime.get("ca_bundle"),
                       "verify_tls": runtime.get("verify_tls", False),
                       "cluster_bringup_timeout_s": runtime.get("cluster_bringup_timeout_s", 3600)},
    }
    hosts = {}
    for key, node in zip(ND_HOSTS, cluster.get("nodes") or []):
        number = key.split("-")[1]
        cimc = node.get("cimc") or {}
        hosts[key] = {"nd_node": {
            "hostname": str(node.get("hostname", key)).upper(),
            "type": node.get("type", "Primary"),
            "role": node.get("role", "secondary"),
            "cimc": {"ip": cimc.get("ip", ""), "user": cimc.get("username", "admin"), "pass_ref": f"ND{number}_CIMC_PASSWORD"},
            "mgmt": {"ip": (node.get("mgmt") or {}).get("ip"), "mask": _prefix((node.get("mgmt") or {}).get("mask", 24)),
                     "gateway": (node.get("mgmt") or {}).get("gateway")},
            "data": {"ip": (node.get("data") or {}).get("ip"), "mask": _prefix((node.get("data") or {}).get("mask", 24)),
                     "gateway": (node.get("data") or {}).get("gateway"), "vlan": (node.get("data") or {}).get("vlan")},
        }}
    return group, hosts


def aipod_services(services: dict) -> dict:
    ntp = list(services.get("ntp_servers") or [])
    return {key: value for key, value in {
        "domain_name": services.get("domain_name", ""),
        "dns_servers": list(services.get("dns_servers") or []),
        "dns_search_domains": list(services.get("dns_search_domains") or []),
        "ntp_servers": ntp,
        "ntp_preferred_server": ntp[0] if ntp else "",
        "timezone": services.get("timezone", "UTC"),
    }.items() if value not in ("", [])}


DOMAIN_ROLES = ("fabric-interconnect", "x-direct")
REDFISH_ROLES = ("ucs-server", "hgx-node")
TARGET_ROLES = DOMAIN_ROLES + REDFISH_ROLES
FI_PASSWORD_REF = "UCS_FI_PASSWORD"
CIMC_PASSWORD_REF = "UCS_CIMC_PASSWORD"
# HGX nodes (C845A / C880A) have their own BMC password: the C880A cannot be claimed, so it is entered on the HGX page.
HGX_PASSWORD_REF = "HGX_BMC_PASSWORD"
DEFAULT_ORGANIZATION = {"organization": "default", "resource_group": "default"}
FACTORY_PASSWORD_MIN = 12


def organizations(state: dict) -> list[dict]:
    """Organization / resource group pairs; the first one is the default for every target."""
    pairs = [{"organization": str(item.get("organization") or "").strip(),
              "resource_group": str(item.get("resource_group") or "").strip()}
             for item in state.get("organizations") or [] if isinstance(item, dict)]
    pairs = [item for item in pairs if item["organization"]]
    if not pairs and (state.get("organization") or state.get("resource_group")):
        pairs = [{"organization": state.get("organization") or "default",
                  "resource_group": state.get("resource_group") or ""}]
    for item in pairs:
        item["resource_group"] = item["resource_group"] or item["organization"]
    return pairs or [dict(DEFAULT_ORGANIZATION)]


def target_from_row(row: dict, legacy: dict | None = None) -> dict:
    legacy = legacy or {}
    address = row.get("ip", "")
    return {"id": host_key(row["hostname"]), "hostname": row["hostname"], "role": row_role(row),
            "pid": row.get("pid", ""), "serial_number": row.get("serial_number", ""), "address": address,
            "static_ip": legacy.get("ip") or address, "netmask": legacy.get("netmask", ""),
            "gateway": legacy.get("gateway", ""), "organization": "", "factory_default": False,
            "override": bool(legacy.get("user") and legacy.get("user") != "admin"),
            "username": legacy.get("user", "") if legacy.get("user") != "admin" else ""}


def registration_targets(rows: list[dict], state: dict | None = None) -> list[dict]:
    """The Claim Targets list: saved targets, or the initial inventory rows with a target role."""
    state = state or {}
    if isinstance(state.get("targets"), list):
        return [dict(item) for item in state["targets"] if isinstance(item, dict) and item.get("hostname")
                and item.get("role") in TARGET_ROLES]
    legacy = state.get("devices") or {}
    return [target_from_row(row, legacy.get(host_key(row["hostname"]))) for row in by_role(rows, *TARGET_ROLES)]


def missing_targets(rows: list[dict], targets: list[dict]) -> list[dict]:
    """Inventory rows with a target role that are not in the list yet."""
    known = {host_key(item["hostname"]) for item in targets}
    return [target_from_row(row) for row in by_role(rows, *TARGET_ROLES) if host_key(row["hostname"]) not in known]


def target_claimable(target: dict) -> bool:
    return is_claimable({"role": target.get("role"), "pid": target.get("pid", ""), "hostname": target["hostname"]})


def target_pass_ref(target: dict) -> str:
    if target.get("override"):
        return pass_ref(host_key(target["hostname"]), "CIMC_PASSWORD")
    if target.get("role") == "hgx-node":
        return HGX_PASSWORD_REF
    return FI_PASSWORD_REF if target.get("role") in DOMAIN_ROLES else CIMC_PASSWORD_REF


def registration_hosts(rows: list[dict], state: dict | None = None) -> dict[str, dict]:
    """UCS claim endpoints in the stage 05/06 host_vars format, keyed by inventory host."""
    state = state or {}
    pairs = organizations(state)
    groups = {item["organization"]: item["resource_group"] for item in pairs}
    hosts = {}
    for target in registration_targets(rows, state):
        key = host_key(target["hostname"])
        role = target["role"]
        domain = role in DOMAIN_ROLES
        default_user = state.get("fi_username" if domain else "cimc_username") or "admin"
        user = (target.get("username") or default_user) if target.get("override") else default_user
        organization = target.get("organization") if target.get("organization") in groups else pairs[0]["organization"]
        address = str(target.get("address") or "").strip()
        static = str(target.get("static_ip") or "").strip() or address
        cimc = {"ip": static, "user": user, "pass_ref": target_pass_ref(target)}
        if role in REDFISH_ROLES and address:
            cimc["dhcp_ip"] = address
        cimc.update({name: str(target[name]).strip() for name in ("netmask", "gateway") if target.get(name)})
        hosts[key] = {"ucs": {
            "device_role": role,
            "pid": target.get("pid", ""),
            "serial_number": target.get("serial_number", ""),
            "platform": "domain" if domain else "standalone",
            "role": target.get("workload_role", "gpu"),
            "hostname": target["hostname"],
            "claim_target": domain_name(target["hostname"]) if domain else key,
            "intersight_claim_supported": target_claimable(target),
            "organization": organization,
            "resource_group": groups[organization],
            "factory_default": bool(target.get("factory_default")) and role in REDFISH_ROLES,
            "cimc": cimc,
        }}
    return hosts


def fabric_key(fabric: dict) -> str:
    settings = fabric.get("backend_settings") or {}
    key = settings.get("key") or re.sub(r"[^a-z0-9]+", "_", str(fabric.get("name", "backend")).lower()).strip("_")
    return key if re.match(r"^[a-z]", key) else f"fabric_{key}"


SWITCH_PASSWORD_REF = "SWITCH_PASSWORD"
BACKEND_TYPES = ("aiVxlanEvpn", "aiRouted")


def backend_fabric_vars(fabrics: list[dict]) -> tuple[dict, dict[str, dict]]:
    """Map nexus_dashboard.fabrics (schema) to the stage-02 be_fabrics/be_fabric_features and be_switch host_vars."""
    be_fabrics, hosts, features = [], {}, {}
    for index, fabric in enumerate(fabrics):
        settings = fabric.get("backend_settings") or {}
        evpn = fabric.get("fabric_settings") or {}
        key = fabric_key(fabric)
        entry = {"key": key, "name": fabric.get("name", key), "bgp_as": evpn.get("bgpAsn", 65100 + 2 * index),
                 "underlay_first_octet": settings.get("underlayFirstOctet", 20 + index),
                 "qos_policy": settings.get("qosPolicy", "AI_Fabric_QOS_400G"),
                 "license_tier": str(fabric.get("licenseTier", "premier")).capitalize()}
        if settings.get("replicationMode"):
            entry["replication_mode"] = settings["replicationMode"]
        if "ptp" in settings:
            entry["ptp"] = bool(settings["ptp"])
        if settings.get("location"):
            entry["location"] = dict(settings["location"])
        be_fabrics.append(entry)
        if index == 0:
            telemetry = fabric.get("telemetry") or {}
            features = {
                "unified_fabric_type": "aimlVxlanEbgp", "bgp_as_mode": "Multi-AS", "enable_evpn": True,
                "fabric_mtu": evpn.get("fabricMtu", 9216), "link_state_routing": "ebgp",
                "enable_ai_ml_qos_policy": settings.get("enableAiMlQosPolicy", True),
                "enable_telemetry": telemetry.get("telemetryCollection", True),
                "telemetry_collection_mode": "out_of_band" if telemetry.get("telemetryMode") == "outofband" else "in_band",
                "telemetry_streaming_protocol": "ipv4",
                "telemetry_vrf": telemetry.get("telemetryVrf", "Telemetry_VRF"),
                "telemetry_source_interface": telemetry.get("telemetrySourceInterface", "loopback0"),
                "use_robot_password": settings.get("useRobotPassword", True),
                "switch_password_ref": SWITCH_PASSWORD_REF,
                "add_switches_without_reload": settings.get("addSwitchesWithoutReload", True),
                "bfd": settings.get("bfd", True), "ptp": settings.get("ptp", True),
                "ptp_source_loopback_id": settings.get("ptpSourceLoopbackId", 0),
                "ptp_domain_id": settings.get("ptpDomainId", 0),
                "real_time_backup": settings.get("realTimeBackup", True),
            }
        for switch in fabric.get("switches") or []:
            if not isinstance(switch, dict) or not switch.get("hostname"):
                continue
            be_switch = {"fabric_key": key, "hostname": str(switch["hostname"]).upper(),
                         "role": switch.get("switchRole", "leaf"), "mgmt_ip": switch.get("ip", ""),
                         "username": switch.get("username", "admin"),
                         "pass_ref": switch.get("passwordRef", SWITCH_PASSWORD_REF)}
            for source, target in (("fabricLinkInterfaces", "fabric_link_interfaces"),
                                   ("breakoutCommands", "breakout_commands")):
                if switch.get(source):
                    be_switch[target] = list(switch[source])
            hosts[host_key(switch["hostname"])] = {"be_switch": be_switch}
    return {"be_fabrics": be_fabrics, "be_fabric_features": features}, hosts


def saved_backend_fabrics(host_vars_dir: Path) -> list[dict]:
    data = _load(Path(host_vars_dir) / "nexus_dashboard" / "backend-fabric.ezai.yaml")
    fabrics = (data.get("nexus_dashboard") or {}).get("fabrics") or []
    return [fabric for fabric in fabrics if isinstance(fabric, dict) and fabric.get("switches")
            and fabric.get("type") in BACKEND_TYPES]


def required_secrets(rows: list[dict], cluster: dict | None = None, fabrics: list[dict] | None = None,
                     registration: dict | None = None) -> dict[str, list[tuple[str, str]]]:
    """Vault keys each stage needs, as (vault key, label) pairs."""
    nd = [("vault_nd_admin_password", "Nexus Dashboard admin password")]
    for index, node in enumerate((cluster or {}).get("nodes") or [], start=1):
        nd.append((f"vault_nd{index}_cimc_password", f"{node.get('hostname', f'nd-{index}')} CIMC password"))
    claim = [("vault_intersight_api_key_id", "Intersight API key ID"),
             ("vault_intersight_api_private_key", "Intersight API secret key (PEM)")]
    labels = {FI_PASSWORD_REF: "Fabric Interconnect password", CIMC_PASSWORD_REF: "CIMC / BMC password",
              HGX_PASSWORD_REF: "HGX BMC password (entered on Compute > HGX Servers)"}
    for values in registration_hosts(rows, registration).values():
        reference = values["ucs"]["cimc"]["pass_ref"]
        claim.append((vault_key(reference), labels.get(reference) or f"{values['ucs']['hostname']} password"))
    claim = list(dict.fromkeys(claim))
    backend = [("vault_nd_admin_password", "Nexus Dashboard admin password"),
               (vault_key(SWITCH_PASSWORD_REF), "Fabric switch admin password")]
    for values in backend_fabric_vars(fabrics or [])[1].values():
        reference = values["be_switch"]["pass_ref"]
        if reference != SWITCH_PASSWORD_REF:
            backend.append((vault_key(reference), f"{values['be_switch']['hostname']} switch password"))
    return {"nd-cluster": nd, "intersight-registration": claim, "backend-fabric": backend}


def build(output_dir: Path, host_vars_dir: Path, rows: list[dict], services: dict, page_state: dict) -> Path:
    """Write <output_dir>/inventory and return its inventory.yml path."""
    root = Path(output_dir) / "inventory"
    group_vars, hosts_dir = root / "group_vars", root / "host_vars"
    for stale in list(hosts_dir.glob("*.yml")) if hosts_dir.is_dir() else []:
        stale.unlink()
    local = {"ansible_connection": "local", "ansible_python_interpreter": "{{ ansible_playbook_python }}"}
    children: dict = {}
    intersight = page_state.get("intersight-registration", {})
    default = organizations(intersight)[0]
    all_vars = {"intersight_api_uri": intersight.get("api_uri") or "https://intersight.com",
                "intersight_resource_group_name": default["resource_group"],
                "intersight_organization_name": default["organization"]}
    all_vars["aipod"] = aipod_services(services)
    _write(group_vars / "all.yml", all_vars)

    cluster = (_load(Path(host_vars_dir) / "nexus_dashboard" / "cluster.ezai.yaml").get("nexus_dashboard") or {}).get("cluster")
    if isinstance(cluster, dict) and cluster.get("nodes"):
        group, nodes = nd_cluster_vars(cluster, services)
        _write(group_vars / "nd_cluster.yml", group)
        for key, values in nodes.items():
            _write(hosts_dir / f"{key}.yml", values)
        bootstrap = [key for key, values in nodes.items() if values["nd_node"]["role"] == "bootstrap"][:1]
        children["nd_cluster"] = {"children": {
            "nd_bootstrap": {"hosts": {key: None for key in bootstrap}},
            "nd_secondary": {"hosts": {key: None for key in nodes if key not in bootstrap}}}, "vars": dict(local)}

    registration = registration_hosts(rows, intersight)
    for key, values in registration.items():
        _write(hosts_dir / f"{key}.yml", values)
    claimable = [key for key, values in registration.items() if values["ucs"]["intersight_claim_supported"]]
    if claimable:
        children["ucs_registration"] = {"hosts": {key: None for key in claimable}, "vars": dict(local)}
    if registration:
        children["ucs_endpoints"] = {"hosts": {key: None for key in registration}, "vars": dict(local)}

    fabric_group, switches = backend_fabric_vars(saved_backend_fabrics(host_vars_dir))
    if switches:
        _write(group_vars / "backend_fabric_switches.yml", fabric_group)
        for key, values in switches.items():
            _write(hosts_dir / f"{key}.yml", values)
        children["backend_fabric_switches"] = {"children": {
            f"backend_fabric_{fabric['key']}": {"hosts": {key: None for key, values in switches.items()
                                                          if values["be_switch"]["fabric_key"] == fabric["key"]}}
            for fabric in fabric_group["be_fabrics"]}}
    elif (group_vars / "backend_fabric_switches.yml").is_file():
        (group_vars / "backend_fabric_switches.yml").unlink()
    _write(root / "inventory.yml", {"all": {"hosts": {"localhost": dict(local)}, "children": children}})
    return root / "inventory.yml"
